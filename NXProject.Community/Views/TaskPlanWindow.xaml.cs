                         .Where(r => r.RowState != DataRowState.Deleted
                             && !ReferenceEquals(r, keep)
                             && contentCols.All(c => string.IsNullOrWhiteSpace(r[c]?.ToString())))
                         .ToList())
                row.Delete();
        }

