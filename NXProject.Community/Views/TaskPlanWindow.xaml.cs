        // Renomeia uma coluna exata para o nome canônico, preservando posição/mapa (migração).
        private void RenameColumnPreservingPosition(string oldName, string newName)
        {
            if (_data == null) return;
            if (!_data.Table.Columns.Contains(oldName) || _data.Table.Columns.Contains(newName)) return;
            _data.Table.Columns[oldName]!.ColumnName = newName;
            if (_data.ColumnSheetMap.TryGetValue(oldName, out var sheetIdx))
            {
                _data.ColumnSheetMap.Remove(oldName);
                _data.ColumnSheetMap[newName] = sheetIdx;
            }
            if (_data.AppendedColumns.Remove(oldName))
                _data.AppendedColumns.Add(newName);
            _dirty = true;
        }

        // Garante as colunas do cronograma no plano aberto (cria com o nome canônico se faltar).
        private void EnsureScheduleColumns()
        {
            if (_data == null) return;

            // Migra a coluna legada "Concluída (X)" para "Status" (estados do DevOps):
            // X → Closed; mantém a posição física na planilha.
            var statusExisting = FindColumn("Status", "Estado", "State");
            var doneCol = _data.Table.Columns.Cast<DataColumn>().Select(c => c.ColumnName)
                .FirstOrDefault(n => n.Trim().StartsWith("Concluída", StringComparison.OrdinalIgnoreCase)
                                  || n.Trim().StartsWith("Concluida", StringComparison.OrdinalIgnoreCase));
            if (doneCol != null && statusExisting == null)
            {
                foreach (DataRow row in _data.Table.Rows)
                {
                    var v = row[doneCol]?.ToString()?.Trim() ?? "";
                    row[doneCol] = string.IsNullOrEmpty(v) ? "" : "Closed";
                }
                _data.Table.Columns[doneCol]!.ColumnName = "Status";
                if (_data.ColumnSheetMap.TryGetValue(doneCol, out var sheetIdx))
                {
                    _data.ColumnSheetMap.Remove(doneCol);
                    _data.ColumnSheetMap["Status"] = sheetIdx;
                }
                if (_data.AppendedColumns.Remove(doneCol))
                    _data.AppendedColumns.Add("Status");
                _dirty = true;
            }

            // Renomeia a coluna legada "Estimado" para "Estimado HH" (mantém a posição).
            RenameColumnPreservingPosition("Estimado", "Estimado HH");
            // "Observações" legada vira "Observação Tramite" — o nome indica que o texto
            // é registrado como tramite (comentário) da Task no DevOps.
            if (ObservationCol is { } legacyObs && !string.Equals(legacyObs, ObservationColumn, StringComparison.Ordinal))
                RenameColumnPreservingPosition(legacyObs, ObservationColumn);
            if (ResourceCol is { } legacyResource && !string.Equals(legacyResource, ResponsibleColumn, StringComparison.Ordinal))
                RenameColumnPreservingPosition(legacyResource, ResponsibleColumn);
            var numberCreated = EnsureNumberColumn();
            EnsureApprovalColumn();
            EnsureRegisterDateColumn();
            if (numberCreated)
                RenumberTaskPlanRows();
            else
                RefreshNumberSortColumn();

            string?[] found =
            {
                ApprovalCol,
                RegisterDateCol,
                _data.Table.Columns.Cast<DataColumn>().Select(c => c.ColumnName)
                    .FirstOrDefault(n => n.Trim().StartsWith("EPIC", StringComparison.OrdinalIgnoreCase)
                                      || n.Trim().StartsWith("Épic", StringComparison.OrdinalIgnoreCase)),
                EpicIdCol,
                FindColumn("Feature", "Nome da Feature"),
                FeatureIdCol,
                FindColumn("Story", "Nome da Story"),
                StoryIdCol,
                FindColumn("Task", "Tarefa", "Nome da Task"),
                FindColumn("ID Devops", "ID DevOps", "IdDevops", "ID_Devops", "ID Dev Ops", "ID Task", "IdTask", "ID_Task"),
                FindColumn("Prioridade", "Priority", "Prio", "Prioridade Task"),
                FindColumn("Estimado HH", "Estimado", "Estimativa", "HH Estimado", "Estimated", "HH"),
                PercConclusaoCol,
                ResourceCol,
                FindColumn("Status", "Estado", "State"),
            };
            for (int i = 0; i < ScheduleColumns.Length; i++)
                if (found[i] == null && !_data.Table.Columns.Contains(ScheduleColumns[i]))
                {
                    _data.Table.Columns.Add(ScheduleColumns[i], typeof(string));
                    _dirty = true;   // coluna nova será gravada no .xlsx no próximo salvar
                }

            // Posição na visão: ID Feature logo após a Feature; ID Story logo após a Story.
            void PlaceAfter(string? idCol, string? parentCol)
            {
                if (idCol == null || parentCol == null) return;
                if (!_data.Table.Columns.Contains(idCol) || !_data.Table.Columns.Contains(parentCol)) return;
                var target = Math.Min(_data.Table.Columns[parentCol]!.Ordinal + 1, _data.Table.Columns.Count - 1);
                _data.Table.Columns[idCol]!.SetOrdinal(target);
            }
            PlaceAfter(EpicIdCol, _data.Table.Columns.Cast<DataColumn>().Select(c => c.ColumnName)
                .FirstOrDefault(n => n.Trim().StartsWith("EPIC", StringComparison.OrdinalIgnoreCase)
                                  || n.Trim().StartsWith("Épic", StringComparison.OrdinalIgnoreCase)));
            PlaceAfter(FeatureIdCol, FindColumn("Feature", "Nome da Feature"));
            PlaceAfter(StoryIdCol, FindColumn("Story", "Nome da Story"));
            if (NumberCol is { } nc) _data.Table.Columns[nc]!.SetOrdinal(0);
            _data.Table.Columns[ApprovalCol!]!.SetOrdinal(1);
            if (RegisterDateCol is { } rc) _data.Table.Columns[rc]!.SetOrdinal(2);

            // Ordem da visão: Estimado HH e Perc_Conclusao antes do Status; ID Task e
            // Responsável imediatamente antes da Descrição da Task; Observações por último.
            var estName    = FindColumn("Estimado HH", "Estimado", "Estimativa", "HH Estimado", "Estimated", "HH");
            var statusName = FindColumn("Status", "Estado", "State");
            if (estName != null && statusName != null
                && _data.Table.Columns[estName]!.Ordinal > _data.Table.Columns[statusName]!.Ordinal)
                _data.Table.Columns[estName]!.SetOrdinal(_data.Table.Columns[statusName]!.Ordinal);
            PlaceAfter(PercConclusaoCol, estName);

            void PlaceBefore(string? col, string? beforeCol)
            {
                if (col == null || beforeCol == null) return;
                if (!_data.Table.Columns.Contains(col) || !_data.Table.Columns.Contains(beforeCol)) return;
                var self = _data.Table.Columns[col]!;
                var target = _data.Table.Columns[beforeCol]!.Ordinal;
                self.SetOrdinal(self.Ordinal < target ? Math.Max(target - 1, 0) : target);
            }
            var descName = FindColumn("Descrição da Task", "Descricao da Task", "Descrição", "Descricao", "Description");
            PlaceBefore(FindColumn("ID Devops", "ID DevOps", "IdDevops", "ID_Devops", "ID Dev Ops", "ID Task", "IdTask", "ID_Task"), descName);
            PlaceBefore(ResourceCol, descName);

            if (ObservationCol is { } obsName)
                _data.Table.Columns[obsName]!.SetOrdinal(_data.Table.Columns.Count - 1);

            NormalizeApprovalValues();
        }

        private bool EnsureNumberColumn()   => EnsureLeadingControlColumn(NumberColumn, NumberCol, 0);
        private void EnsureApprovalColumn()   => EnsureLeadingControlColumn(ApprovalColumn, ApprovalCol, 1);

        // Valor da coluna "Aprovada" para uma Task vinda do DevOps. Quando o campo de aprovação
        // está habilitado na configuração TFS e o work item traz valor, ele manda; caso
        // contrário mantém o padrão do NXProject (task existente no DevOps = aprovada).
        private static string ApprovalValueFromDevOps(TfsImportService.DevOpsTaskInfo info)
        {
            var raw = info.Approved?.Trim();
            if (string.IsNullOrEmpty(raw)) return ApprovalTrue;

            if (IsApprovalYes(raw) || raw.Equals("approved", StringComparison.OrdinalIgnoreCase)
                || raw.Equals("aprovado", StringComparison.OrdinalIgnoreCase)
                || raw.Equals("aprovada", StringComparison.OrdinalIgnoreCase))
                return ApprovalTrue;

            if (IsApprovalNo(raw) || raw.Equals("rejeitado", StringComparison.OrdinalIgnoreCase)
                || raw.Equals("reprovado", StringComparison.OrdinalIgnoreCase))
                return ApprovalFalse;

            return raw;   // valores próprios do processo do cliente aparecem como estão
        }
        private void EnsureRegisterDateColumn() => EnsureLeadingControlColumn(RegisterDateColumn, RegisterDateCol, 2);

        /// <summary>Garante uma coluna de controle fixa no início (posição de visão
        /// <paramref name="viewOrdinal"/>). Se a planilha já tem colunas físicas e esta é
        /// nova, agenda a inserção de uma coluna física em branco na posição correspondente
        /// e reindexa o mapa — assim ela nasce no início do .xlsx, não no fim com prefixo.</summary>
        private bool EnsureLeadingControlColumn(string canonical, string? existing, int viewOrdinal)
        {
            if (_data == null) return false;
            if (existing != null)
            {
                RenameColumnPreservingPosition(existing, canonical);
                _data.Table.Columns[canonical]!.SetOrdinal(viewOrdinal);
                return false;
            }

            _data.Table.Columns.Add(canonical, typeof(string));
            _data.Table.Columns[canonical]!.SetOrdinal(viewOrdinal);
            if (_data.ColumnSheetMap.Count > 0)
            {
                int pos = viewOrdinal + 1;   // posição física (1-based) desejada no início
                foreach (var key in _data.ColumnSheetMap.Keys.ToList())
                    if (_data.ColumnSheetMap[key] >= pos)
                        _data.ColumnSheetMap[key]++;
                _data.ColumnSheetMap[canonical] = pos;
                _data.InsertBlankLeadingColumnsOnSave.Add(pos);
            }
            _dirty = true;
            return true;
        }

        private void RenumberTaskPlanRows()
        {
            if (_data == null || NumberCol is not { } numberCol) return;
            int n = 1;
            foreach (DataRow row in _data.Table.Rows)
                row[numberCol] = (n++).ToString();
            RefreshNumberSortColumn();
        }

        private void RefreshNumberSortColumn()
        {
            if (_data == null || NumberCol is not { } numberCol) return;
            if (!_data.Table.Columns.Contains(NumberSortColumn))
                _data.Table.Columns.Add(NumberSortColumn, typeof(int));

            int fallback = 1;
            foreach (DataRow row in _data.Table.Rows)
            {
                var text = row[numberCol]?.ToString()?.Trim() ?? "";
                row[NumberSortColumn] = int.TryParse(text, out var n) ? n : fallback;
                fallback++;
            }
        }

        // Valores gravados na planilha.
        private const string ApprovalTrue  = "True";
        private const string ApprovalFalse = "False";

        private static bool IsApprovalYes(string? value)
        {
            var v = (value ?? "").Trim();
            return v.Equals("Sim", StringComparison.OrdinalIgnoreCase)
                || v.Equals("S", StringComparison.OrdinalIgnoreCase)
                || v.Equals("Yes", StringComparison.OrdinalIgnoreCase)
                || v.Equals("Y", StringComparison.OrdinalIgnoreCase)
                || v.Equals("True", StringComparison.OrdinalIgnoreCase)
                || v.Equals("1", StringComparison.OrdinalIgnoreCase);
        }

        private static bool IsApprovalNo(string? value)
        {
            var v = (value ?? "").Trim();
            return v.Equals("Nao", StringComparison.OrdinalIgnoreCase)
                || v.Equals("Não", StringComparison.OrdinalIgnoreCase)
                || v.Equals("N", StringComparison.OrdinalIgnoreCase)
                || v.Equals("No", StringComparison.OrdinalIgnoreCase)
                || v.Equals("False", StringComparison.OrdinalIgnoreCase)
                || v.Equals("0", StringComparison.OrdinalIgnoreCase);
        }

        private bool IsApproved(DataRow row)
            => ApprovalCol is { } col && IsApprovalYes(row[col]?.ToString());

        private bool HasUnapprovedInternalTask()
        {
            if (_data == null) return false;
            if (ApprovalCol is not { } approvalCol) return false;
            var idCol = FindColumn("ID Task", "IdTask", "ID_Task", "ID Devops", "ID DevOps", "IdDevops", "ID_Devops", "ID Dev Ops");
            if (idCol == null) return false;
            var taskCol = FindColumn("Task", "Tarefa", "Nome da Task");

            foreach (DataRow row in _data.Table.Rows)
            {
                // Linha vazia (sem Task) não conta como trabalho local a preservar.
                if (taskCol != null && string.IsNullOrWhiteSpace(row[taskCol]?.ToString())) continue;
                // Trabalho local em risco: Aprovada=Não OU ID interno (:I).
                if (IsApprovalNo(row[approvalCol]?.ToString())) return true;
                if ((row[idCol]?.ToString()?.Trim() ?? "").EndsWith(":I", StringComparison.OrdinalIgnoreCase)) return true;
            }

            return false;
        }

        private bool RemoveBlankTaskPlanRows()
        {
            if (_data == null) return false;
            var controlCols = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            if (NumberCol is { } numberCol) controlCols.Add(numberCol);
            if (ApprovalCol is { } approvalCol) controlCols.Add(approvalCol);
            if (RegisterDateCol is { } registerDateCol) controlCols.Add(registerDateCol);

            var rows = _data.Table.Rows.Cast<DataRow>()
                .Where(row => _data.Table.Columns.Cast<DataColumn>()
                    .Where(c => !c.ColumnName.StartsWith("__", StringComparison.Ordinal)
                             && !controlCols.Contains(c.ColumnName))
                    .All(c => string.IsNullOrWhiteSpace(row[c]?.ToString())))
                .ToList();

            foreach (var row in rows)
                _data.Table.Rows.Remove(row);

            if (rows.Count == 0) return false;
            RenumberTaskPlanRows();
            return true;
        }

