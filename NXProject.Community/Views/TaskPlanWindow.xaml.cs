        private void ApplyEpicFilter()
        {
            if (_data == null) return;
            var allLabel = AppStrings.Get("TaskPlan_EpicAll");
            var sel = EpicFilterCombo.SelectedItem as string;

            var parts = new List<string>();
            if (_epicColumn != null && !string.IsNullOrEmpty(sel) && sel != allLabel)
                parts.Add($"[{_epicColumn}] = '{sel.Replace("'", "''")}'");

            var featureCol = FindColumn("Feature", "Nome da Feature");
            var featureSel = FeatureFilterCombo.SelectedItem as string;
            if (featureCol != null && !string.IsNullOrEmpty(featureSel) && featureSel != allLabel)
                parts.Add($"[{featureCol}] = '{featureSel.Replace("'", "''")}'");
            var statusCol = FindColumn("Status", "Estado", "State");
            if (OpenTasksOnlyCheckBox?.IsChecked == true && statusCol != null)
                parts.Add($"([{statusCol}] IS NULL OR [{statusCol}] = '' OR [{statusCol}] <> 'Closed')");
            foreach (var kv in _columnFilters)
            {
                if (!_data.Table.Columns.Contains(kv.Key) || kv.Value.Count == 0) continue;
                var values = string.Join(",", kv.Value.Select(v => $"'{v.Replace("'", "''")}'"));
                parts.Add($"[{kv.Key}] IN ({values})");
            }
            foreach (var kv in _columnColorFilters)
            {
                var colorCol = ExcelTaskPlanService.ColorColPrefix + kv.Key;
                if (!_data.Table.Columns.Contains(colorCol))
                {
                    if (string.IsNullOrEmpty(kv.Value))
                        continue;
                    parts.Add("1 = 0");
                    continue;
                }

                if (string.IsNullOrEmpty(kv.Value))
                    parts.Add($"([{colorCol}] IS NULL OR [{colorCol}] = '')");
                else
                    parts.Add($"[{colorCol}] = '{kv.Value.Replace("'", "''")}'");
            }

            var filter = string.Join(" AND ", parts);
            // A isenção das linhas novas precisa estar no filtro ANTES da inserção: quando o
            // usuário insere, a linha é marcada e o RowFilter em vigor já tem que aceitá-la
            // (senão ela some ao ser comitada). Vale até clicar em "Reaplicar filtro".
            if (filter.Length > 0)
            {
                EnsureNewRowColumn();
                filter = $"({filter}) OR [{NewRowFlagCol}] = '1'";
            }

            _data.Table.DefaultView.RowFilter = filter;
            ApplyEpicColumnVisibility();
            UpdateActiveFilterIndicator();
            UpdateFilteredColumnHeaderMarkers();
        }

