        // Mostra no rodapé quais filtros estão ativos (EPIC/Feature/coluna/cor/em aberto).
        private void UpdateActiveFilterIndicator()
        {
            if (ActiveFilterText == null) return;
            var allLabel = AppStrings.Get("TaskPlan_EpicAll");
            var parts = new List<string>();

            var epic = EpicFilterCombo?.SelectedItem as string;
            if (!string.IsNullOrEmpty(epic) && epic != allLabel) parts.Add($"EPIC = {epic}");
            var feat = FeatureFilterCombo?.SelectedItem as string;
            if (!string.IsNullOrEmpty(feat) && feat != allLabel) parts.Add($"Feature = {feat}");
            if (OpenTasksOnlyCheckBox?.IsChecked == true) parts.Add(AppStrings.Get("TaskPlan_OpenTasksOnly"));

            foreach (var kv in _columnFilters)
                if (kv.Value.Count > 0)
                    parts.Add(kv.Value.Count == 1
                        ? $"{kv.Key} = {kv.Value[0]}"
                        : $"{kv.Key} ({kv.Value.Count})");

            foreach (var kv in _columnColorFilters)
            {
                var label = string.IsNullOrEmpty(kv.Value) ? AppStrings.Get("TaskPlan_ColorNone") : ColorFilterLabel(kv.Value);
                parts.Add($"{kv.Key} ■ {label}");
            }

            if (parts.Count == 0)
            {
                ActiveFilterText.Text = "";
                ActiveFilterText.ToolTip = null;
                return;
            }
            var full = AppStrings.Get("TaskPlan_ActiveFilters", string.Join("   •   ", parts));
            if (HasExemptNewRows())
                full += "   •   " + AppStrings.Get("TaskPlan_NewRowsExempt");
            ActiveFilterText.Text = full;
            ActiveFilterText.ToolTip = full;
        }

        // ── Lembrar filtro: grava/restaura a visão por planilha na config local ──────
        private TaskPlanFilterView CaptureFilterView()
        {
            var allLabel = AppStrings.Get("TaskPlan_EpicAll");
            string ComboVal(System.Windows.Controls.ComboBox? c)
            {
                var v = c?.SelectedItem as string;
                return string.IsNullOrEmpty(v) || v == allLabel ? "" : v;
            }
            var view = new TaskPlanFilterView
            {
                Epic = ComboVal(EpicFilterCombo),
                Feature = ComboVal(FeatureFilterCombo),
                OpenTasksOnly = OpenTasksOnlyCheckBox?.IsChecked == true
            };
            foreach (var kv in _columnFilters)
                view.ColumnFilters[kv.Key] = new List<string>(kv.Value);
            foreach (var kv in _columnColorFilters)
                view.ColorFilters[kv.Key] = kv.Value;
            return view;
        }

        private void ApplyFilterView(TaskPlanFilterView view)
        {
            if (_data == null) return;
            _suppressEpic = true;
            try
            {
                _columnFilters.Clear();
                foreach (var kv in view.ColumnFilters)
                    if (_data.Table.Columns.Contains(kv.Key))
                        _columnFilters[kv.Key] = new List<string>(kv.Value);
                _columnColorFilters.Clear();
                foreach (var kv in view.ColorFilters)
                    _columnColorFilters[kv.Key] = kv.Value;

                if (OpenTasksOnlyCheckBox != null)
                    OpenTasksOnlyCheckBox.IsChecked = view.OpenTasksOnly;

                SelectComboValue(EpicFilterCombo, view.Epic);
                BuildFeatureFilter();
                SelectComboValue(FeatureFilterCombo, view.Feature);
            }
            finally
            {
                _suppressEpic = false;
            }
            ApplyEpicFilter();
        }

        private static void SelectComboValue(System.Windows.Controls.ComboBox? combo, string? value)
        {
            if (combo == null || combo.Items.Count == 0) return;
            if (!string.IsNullOrEmpty(value))
                foreach (var item in combo.Items)
                    if (string.Equals(item?.ToString(), value, StringComparison.OrdinalIgnoreCase))
                    {
                        combo.SelectedItem = item;
                        return;
                    }
            combo.SelectedIndex = 0;
        }

