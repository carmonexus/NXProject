            => _data != null
               && _data.Table.Columns.Contains(NewRowFlagCol)
               && _data.Table.Rows.Cast<DataRow>()
                   .Any(r => r.RowState != DataRowState.Deleted && r[NewRowFlagCol]?.ToString() == "1");

