            }
            catch (IOException)
            {
                MessageBox.Show(this, AppStrings.Get("TaskPlan_Locked"),
                    AppStrings.Get("TaskPlan_Title"), MessageBoxButton.OK, MessageBoxImage.Warning);
            }
            catch (Exception ex)
